import heapq
from collections import Counter

def rearrange_string(s, k):
    """
    Rearranges a string such that the same characters are at least distance k from each other.

    Args:
        s: The input string.
        k: The minimum distance between the same characters.

    Returns:
        The rearranged string if possible, otherwise an empty string.
    """

    if k == 0:
        return s

    counts = Counter(s)
    heap = [(-count, char) for char, count in counts.items()]
    heapq.heapify(heap)

    result = ""
    queue = []

    while heap:
        count, char = heapq.heappop(heap)
        result += char
        count += 1  # Increment count (since it's negative)

        queue.append((count, char))

        if len(queue) >= k:
            count, char = queue.pop(0)
            if count < 0:
                heapq.heappush(heap, (count, char))

    if len(result) != len(s):
        return ""

    return result

