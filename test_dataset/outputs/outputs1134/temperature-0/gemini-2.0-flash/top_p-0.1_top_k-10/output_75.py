class TreeNode:
    def __init__(self, x):
        self.val = x
        self.left = None
        self.right = None

def distanceK(root, target, K):
    """
    Finds all nodes that are a distance K from the target node in a binary tree.

    Args:
        root: The root node of the binary tree.
        target: The target node.
        K: The distance K.

    Returns:
        A list of the values of all nodes that have a distance K from the target node.
    """

    def build_graph(node, parent, graph):
        if node:
            graph[node.val] = []
            if parent:
                graph[node.val].append(parent.val)
                graph[parent.val].append(node.val)
            build_graph(node.left, node, graph)
            build_graph(node.right, node, graph)

    graph = {}
    build_graph(root, None, graph)

    queue = [(target.val, 0)]
    visited = {target.val}
    result = []

    while queue:
        node, dist = queue.pop(0)
        if dist == K:
            result.append(node)
        else:
            for neighbor in graph[node]:
                if neighbor not in visited:
                    queue.append((neighbor, dist + 1))
                    visited.add(neighbor)

    return result

