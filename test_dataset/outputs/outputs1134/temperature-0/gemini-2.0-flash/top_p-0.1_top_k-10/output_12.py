def isNStraightHand(hand, W):
    """
    Determines if Alice can rearrange her hand into groups of size W with consecutive cards.

    Args:
        hand (list of int): Alice's hand of cards.
        W (int): The desired group size.

    Returns:
        bool: True if Alice can rearrange her hand, False otherwise.
    """
    if len(hand) % W != 0:
        return False

    counts = {}
    for card in hand:
        counts[card] = counts.get(card, 0) + 1

    import heapq
    heap = list(counts.keys())
    heapq.heapify(heap)

    while heap:
        first = heapq.heappop(heap)
        if counts[first] == 0:
            continue

        for i in range(W):
            card = first + i
            if card not in counts or counts[card] == 0:
                return False
            counts[card] -= 1

    return True

