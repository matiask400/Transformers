def least_operators(x, target):
    """
    Finds the least number of operators to reach the target.

    Args:
        x: The base number.
        target: The target value.

    Returns:
        The least number of operators used.
    """

    def solve(current_val, num_ops):
        if abs(current_val - target) < 1e-6:
            return num_ops
        if num_ops > 8:
            return float('inf')

        best = float('inf')
        best = min(best, solve(current_val + x, num_ops + 1))
        best = min(best, solve(current_val - x, num_ops + 1))
        best = min(best, solve(current_val * x, num_ops + 1))
        best = min(best, solve(current_val / x, num_ops + 1))
        return best

    return solve(x, 0)


