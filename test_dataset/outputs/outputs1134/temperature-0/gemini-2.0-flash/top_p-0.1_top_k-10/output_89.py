class GridMaster:

    def __init__(self, grid):
        self.grid = grid
        self.row, self.col = None, None
        for i in range(len(grid)):
            for j in range(len(grid[0])):
                if grid[i][j] == -1:
                    self.row, self.col = i, j
                    break
            if self.row is not None:
                break

    def canMove(self, direction: str) -> bool:
        new_row, new_col = self.row, self.col
        if direction == 'U':
            new_row -= 1
        elif direction == 'D':
            new_row += 1
        elif direction == 'L':
            new_col -= 1
        elif direction == 'R':
            new_col += 1
        else:
            return False

        if 0 <= new_row < len(self.grid) and 0 <= new_col < len(self.grid[0]) and self.grid[new_row][new_col] != 0:
            return True
        return False

    def move(self, direction: str):
        if not self.canMove(direction):
            return

        if direction == 'U':
            self.row -= 1
        elif direction == 'D':
            self.row += 1
        elif direction == 'L':
            self.col -= 1
        elif direction == 'R':
            self.col += 1

    def isTarget(self) -> bool:
        return self.grid[self.row][self.col] == 2


def find_shortest_path(grid):
    """
    Finds the shortest path from the robot's starting cell to the target cell.

    Args:
        grid: A 2D matrix representing the grid.

    Returns:
        The minimum distance between the robot's initial starting cell and the target cell.
        Returns -1 if there is no valid path between the cells.
    """

    master = GridMaster(grid)

    def solve():
        graph = {}
        start = (0, 0)
        target = None

        def dfs(row, col, path_len):
            nonlocal target
            if master.isTarget():
                target = (row, col)
            graph[(row, col)] = {}

            directions = {'U': (-1, 0), 'D': (1, 0), 'L': (0, -1), 'R': (0, 1)}
            reverse_directions = {'U': 'D', 'D': 'U', 'L': 'R', 'R': 'L'}

            for direction, (dr, dc) in directions.items():
                new_row, new_col = row + dr, col + dc
                if (new_row, new_col) not in graph and master.canMove(direction):
                    master.move(direction)
                    graph[(row, col)][(new_row, new_col)] = 1
                    graph[(new_row, new_col)] = {}
                    dfs(new_row, new_col, path_len + 1)
                    master.move(reverse_directions[direction])
                    graph[(new_row, new_col)][(row, col)] = 1

        dfs(0, 0, 0)

        if target is None:
            return -1

        queue = [(start, 0)]
        visited = {start}

        while queue:
            (row, col), dist = queue.pop(0)
            if (row, col) == target:
                return dist

            for neighbor in graph[(row, col)]:
                if neighbor not in visited:
                    visited.add(neighbor)
                    queue.append((neighbor, dist + 1))

        return -1

    return solve()


