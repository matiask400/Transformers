def remove_palindromic_subsequences(s):
    """
    Calculates the minimum number of steps to make the given string empty by removing palindromic subsequences.

    Args:
        s: The input string consisting only of letters 'a' and 'b'.

    Returns:
        The minimum number of steps to make the given string empty.
    """

    if not s:
        return 0

    if s == s[::-1]:
        return 1
    else:
        return 2


